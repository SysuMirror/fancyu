CREATE TABLE IF NOT EXISTS chat_icebreaker_cache (
 mode VARCHAR(12) NOT NULL,pair_id BIGINT UNSIGNED NOT NULL,round TINYINT UNSIGNED NOT NULL,
 topics TEXT NOT NULL,source VARCHAR(8) NOT NULL DEFAULT 'llm',
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(mode,pair_id,round)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
