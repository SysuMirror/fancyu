CREATE TABLE IF NOT EXISTS deep_batches (
 batch_key CHAR(10) PRIMARY KEY, status VARCHAR(16) NOT NULL DEFAULT 'open',
 algorithm VARCHAR(32) NOT NULL DEFAULT 'deep-v3-education-weight', plan JSON NULL, stats JSON NULL,
 revision INT NOT NULL DEFAULT 0, approved_revision INT NULL, approved_by VARCHAR(100) NULL,
 published_at DATETIME NULL, last_error VARCHAR(64) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS deep_entries (
 batch_key CHAR(10) NOT NULL, card_id INT NOT NULL, account_id INT NOT NULL,
 snapshot JSON NOT NULL, active BOOLEAN NOT NULL DEFAULT 1,
 PRIMARY KEY(batch_key,card_id),
 FOREIGN KEY(batch_key) REFERENCES deep_batches(batch_key) ON DELETE CASCADE,
 FOREIGN KEY(card_id) REFERENCES accounts(id) ON DELETE CASCADE,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS deep_surveys (account_id INT PRIMARY KEY, data JSON NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS deep_pairs (id INT AUTO_INCREMENT PRIMARY KEY,week_key CHAR(10) NOT NULL,a_id INT NOT NULL,b_id INT NOT NULL,status VARCHAR(16) NOT NULL DEFAULT 'pending',a_agreed BOOLEAN NOT NULL DEFAULT 0,b_agreed BOOLEAN NOT NULL DEFAULT 0,a_wechat VARCHAR(32) NULL,b_wechat VARCHAR(32) NULL,created_at DATETIME NOT NULL,FOREIGN KEY(a_id) REFERENCES accounts(id) ON DELETE CASCADE,FOREIGN KEY(b_id) REFERENCES accounts(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS deep_slots(account_id INT NOT NULL,week_key CHAR(10) NOT NULL,pair_id INT NOT NULL,PRIMARY KEY(account_id,week_key),FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS deep_match_feedback (
 pair_id INT NOT NULL,account_id INT NOT NULL,answer VARCHAR(24) NOT NULL,updated_at DATETIME NOT NULL,
 PRIMARY KEY(pair_id,account_id),FOREIGN KEY(pair_id) REFERENCES deep_pairs(id) ON DELETE CASCADE,
 FOREIGN KEY(account_id) REFERENCES accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;